package com.aeroflow.hub.service.jwt;

import io.jsonwebtoken.Claims;
import io.jsonwebtoken.Jwts;
import io.jsonwebtoken.io.Decoders;
import io.jsonwebtoken.io.DecodingException;
import io.jsonwebtoken.security.Keys;
import java.time.Instant;
import java.util.Date;
import javax.crypto.SecretKey;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.security.core.userdetails.UserDetails;
import org.springframework.stereotype.Service;

@Service
public class JwtService {

    private final SecretKey signingKey;
    private final long expirationMillis;

    public JwtService(
            @Value("${app.security.jwt.secret}") String base64Secret,
            @Value("${app.security.jwt.expiration}") long expirationMillis
    ) {
        if (base64Secret == null || base64Secret.isBlank()) {
            throw new IllegalStateException(
                    "JWT_SECRET_BASE64 is required; set it to a standard Base64-encoded key "
                            + "generated by `openssl rand -base64 32`.");
        }

        byte[] keyBytes = decodeSecret(base64Secret.strip());
        if (keyBytes.length < 32) {
            throw new IllegalStateException(
                    "JWT_SECRET_BASE64 must decode to at least 32 bytes; "
                            + "generate a key with `openssl rand -base64 32`.");
        }
        if (expirationMillis <= 0) {
            throw new IllegalStateException("JWT_EXPIRATION_MS must be greater than zero.");
        }

        this.signingKey = Keys.hmacShaKeyFor(keyBytes);
        this.expirationMillis = expirationMillis;
    }

    private byte[] decodeSecret(String encodedSecret) {
        try {
            if (encodedSecret.contains("-") || encodedSecret.contains("_")) {
                return Decoders.BASE64URL.decode(encodedSecret);
            }
            return Decoders.BASE64.decode(encodedSecret);
        } catch (DecodingException exception) {
            throw new IllegalStateException(
                    "JWT_SECRET_BASE64 must contain a valid standard Base64 or Base64URL-encoded "
                            + "secret. Replace any IntelliJ environment-variable override or placeholder "
                            + "with the output of `openssl rand -base64 32`.",
                    exception);
        }
    }

    public String generateToken(UserDetails userDetails) {
        Instant issuedAt = Instant.now();
        return Jwts.builder()
                .subject(userDetails.getUsername())
                .issuedAt(Date.from(issuedAt))
                .expiration(Date.from(issuedAt.plusMillis(expirationMillis)))
                .signWith(signingKey)
                .compact();
    }

    public String extractUsername(String token) {
        return parseClaims(token).getSubject();
    }

    public boolean isTokenValid(String token, UserDetails userDetails) {
        Claims claims = parseClaims(token);
        return claims.getSubject().equals(userDetails.getUsername())
                && claims.getExpiration().after(new Date());
    }

    private Claims parseClaims(String token) {
        return Jwts.parser()
                .verifyWith(signingKey)
                .build()
                .parseSignedClaims(token)
                .getPayload();
    }
}
